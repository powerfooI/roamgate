import { afterEach, describe, expect, test } from "bun:test";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadOrCreateSessionSecret } from "../config/session-secret";
import { EXIT_FAILURE, EXIT_OK } from "./command";
import { runCli } from "./index";
import { createTestCli, type TestCli } from "./test-context";

const TOKEN = "b".repeat(64);
let cli: TestCli;
afterEach(() => cli?.cleanup());

function tokenPath(testCli: TestCli) {
  return join(testCli.home, ".config", "roamgate", "auth-token");
}

describe("roamgate auth", () => {
  test("show masks the token unless revealed", async () => {
    cli = createTestCli();
    cli.writeConfig("ROAMGATE_PIN=123456\n");
    writeFileSync(tokenPath(cli), `${TOKEN}\n`);
    await runCli(["auth", "show", "--json"], cli.context);
    expect(JSON.parse(cli.output.join("\n"))).toMatchObject({
      method: "token",
      token: "bbbb...bbbb",
      pin_enabled: true,
    });
    cli.output.length = 0;
    await runCli(["auth", "show", "--json", "--reveal"], cli.context);
    expect(JSON.parse(cli.output.join("\n")).token).toBe(TOKEN);
  });

  test("rotate writes a fresh valid token and prints new URLs", async () => {
    cli = createTestCli();
    cli.writeConfig("HOST=127.0.0.1\n");
    writeFileSync(tokenPath(cli), `${TOKEN}\n`);
    expect(await runCli(["auth", "rotate"], cli.context)).toBe(EXIT_OK);
    const rotated = readFileSync(tokenPath(cli), "utf8").trim();
    expect(rotated).toMatch(/^[a-f0-9]{64}$/);
    expect(rotated).not.toBe(TOKEN);
    expect(cli.output).toContain(
      `Open: http://localhost:8787/?token=${rotated}`,
    );
  });

  test("rotate refuses services that use a fixed password", async () => {
    cli = createTestCli();
    cli.writeConfig("ROAMGATE_PASSWORD=correct-horse-battery\n");
    expect(await runCli(["auth", "rotate"], cli.context)).toBe(EXIT_FAILURE);
    expect(existsSync(tokenPath(cli))).toBe(false);
  });

  test("revoke-sessions discards the signing secret under the runtime home", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    const secretPath = join(
      cli.home,
      ".config",
      "roamgate",
      "session-secret.json",
    );
    loadOrCreateSessionSecret(["credential"], secretPath);
    expect(
      await runCli(["auth", "revoke-sessions", "--no-restart"], cli.context),
    ).toBe(EXIT_OK);
    expect(existsSync(secretPath)).toBe(false);
    expect(await runCli(["auth", "revoke-sessions"], cli.context)).toBe(
      EXIT_OK,
    );
    expect(cli.output.at(-1)).toContain("no sessions to revoke");
  });

  test("restarts a running managed service after rotation", async () => {
    // No legacy herdr-gui unit exists (systemctl status exits 4 for it).
    cli = createTestCli({
      runCommand: (argv) => (argv.includes("herdr-gui.service") ? 4 : 0),
    });
    cli.writeConfig("");
    const unit = join(
      cli.home,
      ".config",
      "systemd",
      "user",
      "roamgate.service",
    );
    mkdirSync(join(cli.home, ".config", "systemd", "user"), {
      recursive: true,
    });
    writeFileSync(unit, "# Generated by roamgate service install.\n");
    expect(await runCli(["auth", "rotate"], cli.context)).toBe(EXIT_OK);
    expect(cli.commands).toContainEqual([
      "systemctl",
      "--user",
      "restart",
      "roamgate.service",
    ]);
  });

  test("rotate repairs a corrupt token and revoke-sessions ignores it", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    writeFileSync(tokenPath(cli), "truncated\n");
    expect(await runCli(["auth", "show"], cli.context)).toBe(EXIT_OK);
    expect(cli.output.find((line) => line.startsWith("Token:"))).toContain(
      "invalid",
    );
    expect(
      await runCli(["auth", "revoke-sessions", "--no-restart"], cli.context),
    ).toBe(EXIT_OK);
    expect(await runCli(["auth", "rotate"], cli.context)).toBe(EXIT_OK);
    expect(readFileSync(tokenPath(cli), "utf8").trim()).toMatch(
      /^[a-f0-9]{64}$/,
    );
  });
});
