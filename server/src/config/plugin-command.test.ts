import { afterEach, describe, expect, test, spyOn } from "bun:test";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { computeUrl, readServiceEnv, runPluginCommand } from "./plugin-command";

describe("readServiceEnv", () => {
  test("reads plain values", () => {
    expect(readServiceEnv("HOST=0.0.0.0\nPORT=8791\n", "HOST")).toBe("0.0.0.0");
    expect(readServiceEnv("HOST=0.0.0.0\nPORT=8791\n", "PORT")).toBe("8791");
  });

  test("accepts export prefix, whitespace, and quoted values", () => {
    const contents = "export HOST=\"0.0.0.0\"\n  PORT = '8799'\n";
    expect(readServiceEnv(contents, "HOST")).toBe("0.0.0.0");
    expect(readServiceEnv(contents, "PORT")).toBe("8799");
  });

  test("last occurrence wins and missing keys are undefined", () => {
    expect(readServiceEnv("PORT=1\nPORT=2\n", "PORT")).toBe("2");
    expect(readServiceEnv("HOST=x\n", "PORT")).toBeUndefined();
  });

  test("ignores comments and unrelated keys", () => {
    const contents =
      "# HOST=10.0.0.1\nHERDR_GUI_LOG_LEVEL=info\nHOST=127.0.0.1\n";
    expect(readServiceEnv(contents, "HOST")).toBe("127.0.0.1");
  });
});

describe("computeUrl", () => {
  const dirs: string[] = [];
  function fixture(files: Record<string, string>): string {
    const dir = mkdtempSync(join(tmpdir(), "studio-plugin-"));
    dirs.push(dir);
    for (const [name, text] of Object.entries(files)) {
      writeFileSync(join(dir, name), text);
    }
    return dir;
  }
  afterEach(() => {
    while (dirs.length) {
      rmSync(dirs.pop()!, { recursive: true, force: true });
    }
  });

  test("defaults to loopback when no env file exists", () => {
    expect(computeUrl(fixture({}))).toBe("http://127.0.0.1:8787");
  });

  test("includes the login token for non-loopback binds", () => {
    const dir = fixture({
      "roamgate.env": "HOST=0.0.0.0\nPORT=8791\n",
      "auth-token": "abc123\n",
    });
    expect(computeUrl(dir)).toBe("http://localhost:8791/?token=abc123");
  });

  test("includes the login token for loopback binds", () => {
    const dir = fixture({
      "roamgate.env": "HOST=127.0.0.1\nPORT=8787\n",
      "auth-token": "abc123\n",
    });
    expect(computeUrl(dir)).toBe("http://127.0.0.1:8787/?token=abc123");
  });

  test("new password values take precedence, including empty values", () => {
    const dir = fixture({
      "roamgate.env":
        "HOST=0.0.0.0\nHERDR_GUI_PASSWORD=old\nROAMGATE_PASSWORD=new\n",
      "auth-token": "saved-token\n",
    });
    expect(computeUrl(dir)).toBe("http://localhost:8787");
    writeFileSync(
      join(dir, "roamgate.env"),
      "HOST=0.0.0.0\nHERDR_GUI_PASSWORD=old\nROAMGATE_PASSWORD=\n",
    );
    expect(computeUrl(dir)).toBe("http://localhost:8787/?token=saved-token");
  });

  test("honors exported and quoted entries without a token file", () => {
    const dir = fixture({
      "roamgate.env": 'export HOST="0.0.0.0"\nPORT = "8799"\n',
    });
    expect(computeUrl(dir)).toBe("http://localhost:8799");
  });
});

test("plugin dispatch rejects extra arguments and leaves other CLI commands alone", async () => {
  const error = spyOn(console, "error").mockImplementation(() => {});
  const log = spyOn(console, "log").mockImplementation(() => {});
  try {
    expect(await runPluginCommand(["service", "install"], "9.8.7")).toBeNull();
    expect(
      await runPluginCommand(["plugin", "restart", "--force"], "9.8.7"),
    ).toBe(1);
    expect(await runPluginCommand(["plugin", "version"], "9.8.7")).toBe(0);
    expect(log).toHaveBeenCalledWith("roamgate 9.8.7");
  } finally {
    error.mockRestore();
    log.mockRestore();
  }
});

for (const [verb, exitCode, definitionType] of [
  ["start", 0, "generated"],
  ["restart", 0, "generated"],
  ["restart", 23, "generated"],
  ["restart", 1, "custom"],
] as const) {
  test(`native ${verb} preserves configuration for a ${definitionType} service with exit ${exitCode}`, async () => {
    const root = mkdtempSync(join(tmpdir(), "roamgate-native-plugin-"));
    try {
      const homeDir = join(root, "home");
      const serviceDir = join(homeDir, ".config/systemd/user");
      const configDir = join(homeDir, ".config/roamgate");
      mkdirSync(serviceDir, { recursive: true });
      mkdirSync(configDir, { recursive: true });
      const definition = join(serviceDir, "roamgate.service");
      const binary = join(root, "roamgate");
      const previous =
        (definitionType === "generated"
          ? "# Generated by roamgate service install.\n"
          : "# Custom service definition.\n") +
        "[Service]\nExecStart=/previous-installation/roamgate\n";
      writeFileSync(definition, previous);
      const config = "HOST=127.0.0.1\nPORT=8799\n";
      const token = "a".repeat(64);
      writeFileSync(join(configDir, "roamgate.env"), config);
      writeFileSync(join(configDir, "auth-token"), token);
      const fixture = join(root, "service-fixture.ts");
      writeFileSync(
        binary,
        `#!/bin/sh\nexec '${process.execPath.replaceAll("'", "'\\''")}' '${fixture.replaceAll("'", "'\\''")}' "$0" "$@"\n`,
        { mode: 0o755 },
      );
      writeFileSync(
        fixture,
        `import { appendFileSync } from "node:fs";
import { runServiceCommand } from ${JSON.stringify(join(import.meta.dir, "service-manager.ts"))};
const [binary, ...args] = process.argv.slice(2);
const result = runServiceCommand(args, {
 runtime: { platform: "linux", homeDir: ${JSON.stringify(homeDir)}, execPath: binary, argv: [binary, ...args] },
 runCommand: argv => {
  if (argv.includes("herdr-gui.service")) return 4;
  appendFileSync(${JSON.stringify(join(root, "service.log"))}, JSON.stringify(argv) + "\\n");
  return argv.includes("daemon-reload") ? ${exitCode} : 0;
 }, getLanIPs: () => [], log: () => {}, error: () => {},
});
process.exit(typeof result === "number" ? result : 1);
`,
      );
      expect(await runPluginCommand(["plugin", verb], "9.8.7", binary)).toBe(
        exitCode,
      );
      expect(readFileSync(join(configDir, "roamgate.env"), "utf8")).toBe(
        config,
      );
      expect(readFileSync(join(configDir, "auth-token"), "utf8")).toBe(token);
      if (definitionType === "custom") {
        expect(readFileSync(definition, "utf8")).toBe(previous);
        expect(existsSync(join(root, "service.log"))).toBe(false);
      } else {
        expect(readFileSync(definition, "utf8")).toContain(
          `ExecStart=${binary}\n`,
        );
        expect(readFileSync(definition, "utf8")).not.toContain(
          "/previous-installation",
        );
        expect(readFileSync(join(root, "service.log"), "utf8")).toContain(
          "daemon-reload",
        );
      }
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
}
